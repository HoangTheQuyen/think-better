// Command gen records what every released think-better version installed,
// so the installer can recognize unmodified files in installs made by those
// versions (especially the ones from before install manifests existed).
//
// For each release tag it extracts the tagged source with `git archive`,
// builds that version's binary, runs its `init` for every target, in a
// project and (where the version supports it) with --global, and records the
// SHA-256 of every file written, keyed by skill and by the file's path
// relative to the skill (or workflow) directory. Hashing what the old binary
// actually wrote captures each version's own per-target path rewriting.
//
// Run it from the repository root after a release has been tagged:
//
//	go run ./internal/installer/gen            # or: make known-hashes
//
// and commit internal/installer/known_hashes.json. The data for releases
// made before manifests existed (v1.3.0 and older) never changes; later
// releases are added for completeness. `-check` only reports release tags
// missing from the file (CI warns about them).
package main

import (
	"archive/tar"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"github.com/HoangTheQuyen/think-better/internal/targets"
)

// knownHashes is the file format; keep in sync with internal/installer/knownhashes.go.
type knownHashes struct {
	Comment   string                                    `json:"comment"`
	Versions  []string                                  `json:"versions"`
	Skills    map[string]map[string]map[string][]string `json:"skills"`    // skill -> file -> sha256 -> versions
	Workflows map[string]map[string]map[string][]string `json:"workflows"` // skill -> workflow file -> sha256 -> versions
}

const comment = "Generated by `go run ./internal/installer/gen` (make known-hashes). DO NOT EDIT."

func main() {
	out := flag.String("out", "internal/installer/known_hashes.json", "file to write")
	check := flag.Bool("check", false, "only report release tags missing from -out")
	only := flag.String("versions", "", "comma-separated tags to record (default: every v* tag merged into HEAD)")
	flag.Parse()

	if err := run(*out, *only, *check); err != nil {
		fmt.Fprintf(os.Stderr, "gen: %v\n", err)
		os.Exit(1)
	}
}

func run(out, only string, check bool) error {
	versions, err := releaseTags(only)
	if err != nil {
		return err
	}
	if check {
		return checkCovered(out, versions)
	}

	kh := knownHashes{
		Comment:   comment,
		Versions:  versions,
		Skills:    map[string]map[string]map[string][]string{},
		Workflows: map[string]map[string]map[string][]string{},
	}
	work, err := os.MkdirTemp("", "think-better-known-hashes-")
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(work) }()

	for _, v := range versions {
		if err := recordVersion(&kh, v, filepath.Join(work, v)); err != nil {
			return fmt.Errorf("%s: %w", v, err)
		}
	}
	data, err := json.MarshalIndent(kh, "", "  ")
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, append(data, '\n'), 0o644); err != nil {
		return err
	}
	fmt.Printf("gen: %d versions -> %s\n", len(versions), out)
	return nil
}

var releaseTag = regexp.MustCompile(`^v\d+\.\d+\.\d+(-[0-9A-Za-z.]+)?$`)

// releaseTags returns the tags to record, oldest first.
func releaseTags(only string) ([]string, error) {
	var tags []string
	if only != "" {
		tags = strings.Split(only, ",")
	} else {
		outb, err := exec.Command("git", "tag", "--merged", "HEAD", "--list", "v*").Output()
		if err != nil {
			return nil, fmt.Errorf("listing tags (needs the full git history): %w", err)
		}
		tags = strings.Fields(string(outb))
	}
	var keep []string
	for _, t := range tags {
		if t = strings.TrimSpace(t); releaseTag.MatchString(t) {
			keep = append(keep, t)
		}
	}
	sort.Slice(keep, func(i, j int) bool { return versionLess(keep[i], keep[j]) })
	return keep, nil
}

func versionLess(a, b string) bool {
	pa, pb := versionParts(a), versionParts(b)
	for i := range pa {
		if pa[i] != pb[i] {
			return pa[i] < pb[i]
		}
	}
	return a < b
}

func versionParts(v string) [3]int {
	core, _, _ := strings.Cut(strings.TrimPrefix(v, "v"), "-")
	var p [3]int
	for i, s := range strings.SplitN(core, ".", 3) {
		p[i], _ = strconv.Atoi(s)
	}
	return p
}

func checkCovered(out string, versions []string) error {
	data, err := os.ReadFile(out)
	if err != nil {
		return err
	}
	var kh knownHashes
	if err := json.Unmarshal(data, &kh); err != nil {
		return fmt.Errorf("%s: %w", out, err)
	}
	have := map[string]bool{}
	for _, v := range kh.Versions {
		have[v] = true
	}
	var missing []string
	for _, v := range versions {
		if !have[v] {
			missing = append(missing, v)
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("%s does not cover %s; run `make known-hashes` and commit the result", out, strings.Join(missing, ", "))
	}
	fmt.Printf("gen: %s covers all %d release tags\n", out, len(versions))
	return nil
}

// recordVersion builds version v in dir and records what its init writes.
func recordVersion(kh *knownHashes, v, dir string) error {
	src := filepath.Join(dir, "src")
	if err := extract(v, src); err != nil {
		return err
	}
	bin, err := build(src, filepath.Join(dir, "bin"))
	if err != nil {
		return err
	}
	for i := range targets.Targets {
		t := &targets.Targets[i]
		project := filepath.Join(dir, "project-"+t.Name)
		if ok, err := runInit(bin, project, filepath.Join(dir, "home-"+t.Name), "--ai", t.Name); err != nil {
			return err
		} else if ok {
			collect(kh, v, project, layout(project, t))
		}
		g, err := t.Global()
		if err != nil {
			continue // no --global for this target (today)
		}
		home := filepath.Join(dir, "global-"+t.Name)
		if ok, err := runInit(bin, filepath.Join(dir, "cwd-"+t.Name), home, "--ai", t.Name, "--global"); err != nil {
			return err
		} else if ok {
			collect(kh, v, home, g)
		}
	}
	return nil
}

// layout returns the variant of project target t that matches what a
// release wrote in base: releases from before a target's skills moved used
// one of its legacy locations (e.g. Copilot's .github/prompts/<skill>/).
func layout(base string, t *targets.AITarget) *targets.AITarget {
	isDir := func(rel string) bool {
		fi, err := os.Stat(filepath.Join(base, filepath.FromSlash(rel)))
		return err == nil && fi.IsDir()
	}
	if isDir(t.SkillsRoot()) {
		return t
	}
	for _, l := range t.Legacy() {
		if isDir(l.SkillsRoot()) {
			return l
		}
	}
	return t
}

// extract writes the tree of tag v to dst.
func extract(v, dst string) error {
	cmd := exec.Command("git", "archive", "--format=tar", v)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	data, err := cmd.Output()
	if err != nil {
		return fmt.Errorf("git archive: %w: %s", err, stderr.String())
	}
	tr := tar.NewReader(bytes.NewReader(data))
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return nil
		}
		if err != nil {
			return err
		}
		if !filepath.IsLocal(hdr.Name) {
			return fmt.Errorf("unexpected path %q in archive", hdr.Name)
		}
		p := filepath.Join(dst, filepath.FromSlash(hdr.Name))
		switch hdr.Typeflag {
		case tar.TypeDir:
			if err := os.MkdirAll(p, 0o755); err != nil {
				return err
			}
		case tar.TypeReg:
			if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
				return err
			}
			body, err := io.ReadAll(tr)
			if err != nil {
				return err
			}
			if err := os.WriteFile(p, body, 0o644); err != nil {
				return err
			}
		}
	}
}

// build compiles the version's command (cmd/make-decision before v1.1.0,
// cmd/think-better since) and returns the binary's path.
func build(src, binDir string) (string, error) {
	entries, err := os.ReadDir(filepath.Join(src, "cmd"))
	if err != nil {
		return "", err
	}
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		bin := filepath.Join(binDir, e.Name())
		if os.PathSeparator == '\\' {
			bin += ".exe"
		}
		cmd := exec.Command("go", "build", "-o", bin, "./cmd/"+e.Name())
		cmd.Dir = src
		cmd.Env = append(os.Environ(), "CGO_ENABLED=0", "GOWORK=off", "GOFLAGS=")
		if outb, err := cmd.CombinedOutput(); err != nil {
			return "", fmt.Errorf("go build: %w\n%s", err, outb)
		}
		return bin, nil
	}
	return "", errors.New("no command under cmd/")
}

// runInit runs `bin init args...` in cwd with home as the home directory.
// It reports false (and no error) when that version rejects the arguments,
// e.g. a target or --global it did not support yet.
func runInit(bin, cwd, home string, args ...string) (bool, error) {
	for _, d := range []string{cwd, home} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			return false, err
		}
	}
	cmd := exec.Command(bin, append([]string{"init"}, args...)...)
	cmd.Dir = cwd
	cmd.Env = append(os.Environ(), "HOME="+home, "USERPROFILE="+home, "THINK_BETTER_AI=", "MAKE_DECISION_AI=")
	if outb, err := cmd.CombinedOutput(); err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			fmt.Printf("gen: %s init %s: skipped (exit %d): %s\n", filepath.Base(bin), strings.Join(args, " "),
				exit.ExitCode(), firstLine(outb))
			return false, nil
		}
		return false, err
	}
	return true, nil
}

func firstLine(b []byte) string {
	line, _, _ := strings.Cut(strings.TrimSpace(string(b)), "\n")
	return line
}

// collect records every file under base, located with the current layout of
// target t (skill files under its skills root, workflows in its workflow
// directory). Files elsewhere belong to layouts no longer used and are skipped.
func collect(kh *knownHashes, v, base string, t *targets.AITarget) {
	root := t.SkillsRoot()
	wfDir := path.Clean(t.WorkflowDir())
	// Workflows reference their skill as <skills root><skill>/...
	owner := regexp.MustCompile(regexp.QuoteMeta(root) + `([A-Za-z0-9_.-]+)/`)

	_ = filepath.WalkDir(base, func(p string, d fs.DirEntry, err error) error {
		if err != nil || !d.Type().IsRegular() {
			return err
		}
		rel, err := filepath.Rel(base, p)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		name := path.Base(rel)
		if name == ".think-better.json" || name == ".think-better-workflows.json" {
			return nil
		}
		data, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		if rest, ok := strings.CutPrefix(rel, root); ok && strings.Contains(rest, "/") {
			skill, file, _ := strings.Cut(rest, "/")
			add(kh.Skills, skill, file, data, v)
			return nil
		}
		if t.HasWorkflows() && path.Dir(rel) == wfDir {
			m := owner.FindSubmatch(data)
			if m == nil {
				fmt.Printf("gen: %s %s: %s names no skill; skipped\n", v, t.Name, rel)
				return nil
			}
			add(kh.Workflows, string(m[1]), name, data, v)
		}
		return nil
	})
}

func add(m map[string]map[string]map[string][]string, skill, file string, data []byte, v string) {
	if m[skill] == nil {
		m[skill] = map[string]map[string][]string{}
	}
	if m[skill][file] == nil {
		m[skill][file] = map[string][]string{}
	}
	h := sha256Hex(data)
	for _, have := range m[skill][file][h] {
		if have == v {
			return
		}
	}
	m[skill][file][h] = append(m[skill][file][h], v)
}

func sha256Hex(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}
